"""Validate the published dataset and write docs/DATA_QUALITY.md.

Run before publishing. Checks row counts, key uniqueness, field coverage,
value ranges and cross-source agreement, and fails loudly on anything that
would mislead someone using the data.
"""
from pathlib import Path

import numpy as np
import pandas as pd

REPORT = []
FAIL = []


def log(s=''):
    print(s)
    REPORT.append(s)


def check(name, ok, detail=''):
    mark = 'PASS' if ok else 'FAIL'
    log(f'| {name} | {mark} | {detail} |')
    if not ok:
        FAIL.append(name)


m = pd.read_csv('data/master/player_seasons.csv', low_memory=False)
m['season'] = m.season.astype(str)

log('# Data quality report')
log()
log(f'Generated by `scripts/validate.py`. Master table: '
    f'**{len(m):,} rows x {m.shape[1]} columns**.')
log()
log('## Structural checks')
log()
log('| Check | Result | Detail |')
log('|---|---|---|')

dupes = m.duplicated(['league', 'season', 'team', 'player']).sum()
check('Primary key unique (league/season/team/player)', dupes == 0,
      f'{dupes} duplicates')
check('Seasons present', set(m.season) == {'2425', '2526'},
      ', '.join(sorted(set(m.season_label))))
check('Five leagues', m.league.nunique() == 5, f'{m.league.nunique()} leagues')
check('No all-empty columns', (m.notna().sum() == 0).sum() == 0,
      f'{(m.notna().sum() == 0).sum()} empty columns')
neg = [c for c in ('nineties', 'us_shots', 'ss_touches', 'fifa_value_eur')
       if c in m.columns and (pd.to_numeric(m[c], errors='coerce') < 0).any()]
check('No negative counts', not neg, ', '.join(neg) if neg else 'none')
age_ok = m.age.dropna().between(14, 45).all()
check('Ages plausible (14-45)', age_ok,
      f'{m.age.min():.0f}-{m.age.max():.0f}')
pct_cols = [c for c in m.columns if c.endswith('Percentage')]
bad_pct = [c for c in pct_cols
           if not pd.to_numeric(m[c], errors='coerce').dropna().between(0, 100).all()]
check('Percentages within 0-100', not bad_pct,
      f'{len(pct_cols)} percentage columns checked')

log()
log('## Field coverage')
log()
log('| Field group | Populated | Share |')
log('|---|---|---|')
for label, col in [('FBref basics (goals)', 'fb_gls'),
                   ('Understat xG', 'us_np_xg'),
                   ('SofaScore detail', 'ss_clearances'),
                   ('SoFIFA value', 'fifa_value_eur'),
                   ('SoFIFA contract end', 'fifa_contract_end'),
                   ('SoFIFA pace', 'fifa_pace')]:
    if col in m.columns:
        k = m[col].notna().sum()
        log(f'| {label} | {k:,} | {k/len(m)*100:.0f}% |')

log()
log('## Cross-source agreement')
log()
log('Understat and SofaScore count goals independently. Large disagreement '
    'would indicate a bad name join.')
log()
if 'us_np_goals' in m.columns and 'ss_goals' in m.columns:
    both = m[m.us_np_goals.notna() & m.ss_goals.notna()].copy()
    # SofaScore goals include penalties, Understat np_goals do not
    both['diff'] = both.ss_goals - both.us_np_goals
    within = (both['diff'].between(-1, 6)).mean() * 100
    corr = both.ss_goals.corr(both.us_np_goals)
    log(f'- Rows comparable: **{len(both):,}**')
    log(f'- Correlation (SofaScore goals vs Understat non-penalty goals): '
        f'**{corr:.3f}**')
    log(f'- Within expected band: **{within:.1f}%**')
    check('Goal counts correlate across sources', corr > 0.9, f'r = {corr:.3f}')

log()
log('## Companion files')
log()
log('| File | Rows | Columns |')
log('|---|---|---|')
for f in ['data/master/player_seasons.csv', 'data/master/player_seasons_adj.csv',
          'data/clean/sofascore_player_seasons.csv', 'data/clean/sofifa_players.csv',
          'data/clean/understat_players.csv', 'data/clean/barca_shots.csv',
          'data/clean/wc_shots.csv', 'data/clean/barca_passing_network.csv']:
    p = Path(f)
    if p.exists():
        d = pd.read_csv(p, low_memory=False)
        log(f'| `{f}` | {len(d):,} | {d.shape[1]} |')

log()
log('## Known limitations')
log()
for s in [
    'SoFIFA is a **current snapshot**, so value/contract/attributes do not vary '
    'by season and only match players still in the top-5 leagues (73%).',
    'SoFIFA values are **EA\'s model, not Transfermarkt quotes**; pace and other '
    'attributes are **scouted estimates, not measured**.',
    'FBref currently serves its advanced tables near-empty '
    '(possession, gca, passing, defense) - SofaScore replaces them here.',
    'Name matching across sources is imperfect; ambiguous matches are left null '
    'rather than guessed, so 4-6% of rows lack one source.',
    'Squad membership reflects 2024/25-2025/26 and drifts after transfer windows.',
    'No pass-level event data: chance-creation origins and true pass maps are '
    'unavailable without a paid provider.',
]:
    log(f'- {s}')

Path('docs').mkdir(exist_ok=True)
Path('docs/DATA_QUALITY.md').write_text('\n'.join(REPORT) + '\n', encoding='utf-8')
print('\n-> docs/DATA_QUALITY.md')
if FAIL:
    print('FAILED CHECKS:', ', '.join(FAIL))
    raise SystemExit(1)
print('all checks passed')
